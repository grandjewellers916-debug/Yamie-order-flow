// End-to-end API check of the order rules (run against test/server.mjs).
const B = 'http://localhost:' + (process.env.PORT || 8788) + '/api/';
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('ok  ', m); } else { fail++; console.log('FAIL', m); } };
async function call(tok, p, body) {
  const r = await fetch(B + p, { method: body ? 'POST' : 'GET', headers: { 'content-type': 'application/json', ...(tok ? { authorization: 'Bearer ' + tok } : {}) }, body: body ? JSON.stringify(body) : undefined });
  return { s: r.status, d: await r.json() };
}
const login = async (userId, pin) => (await call(null, 'login', { userId, pin })).d.token;
let A = await login('admin', '1986');
ok(!!A, 'admin logs in with first-run PIN');
await call(A, 'mypin', { pin: '4321', name: 'Praveen' });
A = await login('admin', '4321');
const cfg = await call(A, 'user', { user: { name: 'Meera', role: 'manager', pin: '3333' } });
const mgrId = cfg.d.users.find((u) => u.name === 'Meera').id;
const cfg2 = await call(A, 'user', { user: { name: 'Anu', role: 'staff', pin: '1111' } });
const stId = cfg2.d.users.find((u) => u.name === 'Anu').id;
const M = await login(mgrId, '3333'), St = await login(stId, '1111');
ok(M && St, 'manager and staff log in');
ok((await call(St, 'rates', { rates: { k18: 9000 } })).s === 403, 'staff cannot change rates');
await call(M, 'rates', { rates: { k22: 11800, k18: 9655, k14: 7520, k9: 4830, pt: 4200, ag: 160 } });
await call(M, 'vendors', { vendors: [{ name: 'Demo Setters', phone: '9000000102', lead: 15 }] });

// create
const item = { id: 'i1', product: 'Solitaire ring', qty: 1, purity: '18k', colour: 'White', wt: 3.2, stones: [{ type: 'labgrown', ct: 1, charge: 42000 }], mkMode: 'pct', mk: 14, photos: [] };
let r = await call(St, 'order', { create: true, order: { cust: { name: 'Test Customer', phone: '+91 9000000001', src: 'Walk-in' }, items: [item], pays: [{ id: 'x', amt: 5, ok: true }], ono: 'HACK' } });
let o = r.d.order;
ok(r.s === 200 && o.status === 'enquiry' && !o.ono && o.pays.length === 0, 'staff creates enquiry; server strips payments / numbers');
const save = async (tok, ord) => { const x = await call(tok, 'order', { order: ord, baseRev: ord.rev }); if (x.s === 200) o = x.d.order; return x; };
// estimate
const est = { v: 1, total: 85600, sub: 83101, metal: 30896, rates: { k18: 9655 }, items: [item], lines: [] };
r = await save(St, { ...o, status: 'estimate', ests: [est] });
ok(r.s === 200 && /^EST-\d{4}-0001$/.test(o.estNo) && o.ests[0].no === o.estNo && o.ests[0].valid, 'estimate gets EST number and validity from the server: ' + o.estNo);
r = await call(St, 'order', { order: { ...o, status: 'approved' }, baseRev: o.rev - 1 });
ok(r.s === 409, 'stale save is refused (changed on another device)');
r = await save(St, { ...o, status: 'approved' });
ok(r.s === 400 && /approval/.test(r.d.error), 'cannot mark approved without approval evidence');
r = await save(St, { ...o, status: 'approved', approval: { v: 1, ch: 'WhatsApp', ev: 'OK go ahead' } });
ok(r.s === 200 && o.approval.by === 'Anu', 'approval recorded');
// advance: staff tries to self-verify
r = await save(St, { ...o, pays: [{ id: 'p1', kind: 'advance', amt: 17120, mode: 'UPI', ref: 'UTR1', ok: { by: 'Anu' } }] });
ok(r.s === 200 && o.pays[0].ok === null, 'staff payment is saved unverified (cannot self-verify)');
r = await save(St, { ...o, pays: o.pays.concat([{ id: 'p2', kind: 'advance', amt: 10, mode: 'UPI', ref: 'utr1' }]) });
ok(r.s === 400 && /already recorded/.test(r.d.error), 'duplicate receipt reference refused');
r = await save(St, { ...o, status: 'confirmed' });
ok(r.s === 400 && /below the minimum/.test(r.d.error), 'confirm refused below 20% VERIFIED advance');
r = await save(St, { ...o, pays: [{ ...o.pays[0], ok: { by: 'Anu' } }] });
ok(r.s === 403, 'staff cannot verify a payment');
r = await save(M, { ...o, pays: [{ ...o.pays[0], ok: { by: 'x' } }] });
ok(r.s === 200 && o.pays[0].ok.by === 'Meera', 'manager verifies payment (stamped by server)');
r = await save(St, { ...o, status: 'confirmed', lock: 'full' });
ok(r.s === 400 && /Rate lock/.test(r.d.error), 'booking advance cannot lock the full metal rate');
r = await save(St, { ...o, status: 'confirmed', lock: 'none', promise: '2020-01-01' });
ok(r.s === 200 && /^YOR-\d{4}-0001$/.test(o.ono) && o.promise > '2026-01-01' && o.lock === 'none', `order confirmed ${o.ono}, promise ${o.promise} set by server`);
const ono = o.ono;
r = await save(St, { ...o, items: [{ ...item, wt: 5 }], status: 'enquiry' });
ok(r.s === 403, 'confirmed order cannot be sent back to enquiry by staff');
// vendor
r = await save(St, { ...o, status: 'vendor', vendor: { name: 'Demo Setters', etd: '2099-01-01' } });
ok(r.s === 403, 'staff cannot assign vendor');
const farEtd = new Date(Date.now() + 60 * 864e5).toISOString().slice(0, 10);
r = await save(M, { ...o, status: 'vendor', vendor: { name: 'Demo Setters', etd: farEtd, cost: 50000 } });
ok(r.s === 200 && o.promise > farEtd && o.log.some((l) => /Promised delivery moved/.test(l.a)), 'late ETD moves promise and logs approval');
const st = await call(St, 'state');
ok(st.d.orders[0].vendor.cost === null, 'vendor cost hidden from staff');
ok(st.d.vendors.every((v) => !v.phone) && (await call(M, 'state')).d.vendors.some((v) => v.phone), 'vendor phone hidden from staff, shown to manager');
r = await save(St, { ...st.d.orders[0], vendor: { ...st.d.orders[0].vendor, sentAt: Date.now() } });
ok(r.s === 200, 'staff saves without seeing cost');
const mv = await call(M, 'state');
ok(mv.d.orders[0].vendor.cost === 50000, 'cost kept on server after staff save');
r = await save(St, { ...o, status: 'production', vendor: { ...o.vendor, ackAt: Date.now() } });
ok(r.s === 200 && o.status === 'production', 'in production');
r = await save(St, { ...o, status: 'received', recv: [{ wts: {}, pcs: 1 }] });
ok(r.s === 400, 'receive needs actual weights');
r = await save(St, { ...o, status: 'received', recv: [{ wts: { i1: 3.31 }, pcs: 1 }] });
ok(r.s === 200, 'received');
r = await save(St, { ...o, status: 'qc_ok', qc: [{ ok: true, checks: { a: true } }] });
ok(r.s === 403, 'staff cannot approve QC');
r = await save(M, { ...o, status: 'qc_ok', qc: [{ ok: true, checks: { a: true, b: false } }] });
ok(r.s === 400, 'QC approve needs every check');
r = await save(M, { ...o, status: 'qc_fail', qc: [{ ok: false, checks: {}, note: 'Loose prong' }] });
ok(r.s === 200, 'QC rejected');
r = await save(St, { ...o, status: 'ready' });
ok(r.s === 403 || r.s === 400, 'cannot jump to ready after QC rejection');
r = await save(St, { ...o, status: 'rework' }); ok(r.s === 200, 'rework');
r = await save(St, { ...o, status: 'received', recv: o.recv.concat([{ wts: { i1: 3.3 }, pcs: 1 }]) }); ok(r.s === 200, 're-received');
r = await save(M, { ...o, status: 'qc_ok', qc: o.qc.concat([{ ok: true, checks: { a: true, b: true } }]) }); ok(r.s === 200, 'QC approved');
r = await save(St, { ...o, status: 'final', finals: [{ v: 1, total: 90000, needCust: true, varPct: 5.1 }] }); ok(r.s === 200, 'final price saved');
r = await save(St, { ...o, status: 'final_ok' }); ok(r.s === 403, 'staff cannot approve final price');
r = await save(M, { ...o, status: 'final_ok' }); ok(r.s === 200 && o.finals[0].ok.by === 'Meera', 'final approved');
r = await save(St, { ...o, status: 'ready' }); ok(r.s === 200 && o.readyAt, 'ready');
r = await save(St, { ...o, status: 'closed', handover: { to: 'Test' } });
ok(r.s === 400 && /invoice/.test(r.d.error), 'close needs invoice');
r = await save(St, { ...o, inv: { no: 'INV-9', amt: 90000 } }); ok(r.s === 200, 'invoice linked');
r = await save(St, { ...o, status: 'closed', handover: { to: 'Test', exception: 'trust' } });
ok(r.s === 400 && /balance/.test(r.d.error), 'staff cannot close with balance, even with an exception');
r = await save(St, { ...o, pays: o.pays.concat([{ id: 'p3', kind: 'balance', amt: 90000 - 17120, mode: 'Card', ref: 'C1' }]) }); ok(r.s === 200, 'balance recorded');
r = await save(M, { ...o, pays: o.pays.map((p) => ({ ...p, ok: p.ok || { by: 'x' } })) }); ok(r.s === 200, 'balance verified');
r = await save(St, { ...o, status: 'closed', handover: { to: 'Test Customer' } });
ok(r.s === 200 && o.status === 'closed' && o.ono === ono, 'closed with invoice, payment and handover');
// numbers stay unique
const o2 = (await call(St, 'order', { create: true, order: { cust: { name: 'B' }, items: [item] } })).d.order;
r = await call(St, 'order', { order: { ...o2, status: 'estimate', ests: [est] }, baseRev: o2.rev });
ok(r.d.order.estNo.endsWith('-0002'), 'second estimate gets the next number');
ok((await call(St, 'order-delete', { id: o.id })).s === 403, 'staff cannot delete a confirmed order');
ok((await call(St, 'bk/list', {})).s === 403 && (await call(A, 'bk/list', {})).s === 200, 'backup is admin only');
const ch = await call(St, 'changes?since=0');
ok(ch.d.orders.length >= 2, 'changes feed returns orders');
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
